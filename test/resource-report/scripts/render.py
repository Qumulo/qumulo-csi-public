"""Render the Resource Consumption Report (markdown) from one run directory.
usage: scripts/render.py <run-root> [<output.md>]
<run-root> holds baseline/array-{A,B}.json, footprint/summary.json (+ samples), after/array-{A,B}.json,
leftovers.txt and meta.json, as written by `./run.sh report`. An optional <run-root>/findings.md (the written
analysis) is placed after the header. Default output: <run-root>/RESOURCE-CONSUMPTION-REPORT.md"""
import json, re, sys
from datetime import datetime, timezone
from pathlib import Path

GiB, MiB = 2**30, 2**20


def load(p):
    p = Path(p)
    return json.loads(p.read_text()) if p.exists() else None


def fmt(v, nd=1):
    if v is None:
        return "–"
    if isinstance(v, float):
        return f"{v:,.{nd}f}"
    return f"{v:,}" if isinstance(v, int) else str(v)


def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(fmt(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def used(inv):
    fs = inv["file_system"]
    return int(fs["total_size_bytes"]) - int(fs["free_size_bytes"])


def csi_counts(inv):
    return {"exports": len(inv.get("exports", [])), "csi_exports": len(inv.get("exports_csi", [])),
            "quotas": len(inv.get("quotas", [])), "snapshots": len(inv.get("snapshots", [])),
            "policies": len(inv.get("snapshot_policies", [])),
            "repl_source": len(inv["replication_source"]) if isinstance(inv.get("replication_source"), list) else 0,
            "repl_target": len(inv["replication_target"]) if isinstance(inv.get("replication_target"), list) else 0,
            "csi_dirs": sum(1 for d in inv.get("dir_aggregates", []) if "csi" in d["path"])}


def main():
    root = Path(sys.argv[1])
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else root / "RESOURCE-CONSUMPTION-REPORT.md"
    meta = load(root / "meta.json") or {}
    summ = load(root / "footprint" / "summary.json")
    base = {s: load(root / "baseline" / f"array-{s}.json") for s in "AB"}
    after = {s: load(root / "after" / f"array-{s}.json") for s in "AB"}
    left = (root / "leftovers.txt").read_text() if (root / "leftovers.txt").exists() else "(not checked)"
    sc = {x["name"]: x for x in summ["scenarios"]} if summ else {}

    L = []
    w = L.append
    w("# Qumulo CSI driver: resource consumption report\n")
    w(f"**Build:** `{meta.get('driver_commit', '?')}` (driver {meta.get('driver_version', '?')}, {meta.get('go', '')}) · "
      f"**Run:** {meta.get('started', '?')} → {meta.get('finished', '?')} · **Host:** {meta.get('host', '?')}\n")
    w("| Array | Address | Cluster | Software | Nodes | Usable | Used before → after |")
    w("|---|---|---|---|---|---|---|")
    for s in "AB":
        b, a = base[s], after[s] or base[s]
        if not b:
            continue
        w(f"| {s} | `{b['api'].split('//')[1].split(':')[0]}` | {b['cluster']['cluster_name']} | {b['version']['revision_id']} "
          f"| {sum(1 for n in b['nodes'] if n['node_status'] == 'online')}/{len(b['nodes'])} online "
          f"| {int(b['file_system']['total_size_bytes']) / GiB:.1f} GiB | {used(b) / MiB:.1f} → {used(a) / MiB:.1f} MiB |")
    w("")
    w(f"> Generated by `test/resource-report/run.sh report` (see `test/resource-report/README.md`) from run "
      f"`{meta.get('run_id', root.name)}`. The tables are produced by the suite; raw samples, logs and metric scrapes "
      "stay with the run folder and are not committed, because they carry array addresses.\n")
    findings = root / "findings.md"
    if findings.exists():
        w(findings.read_text().rstrip() + "\n\n---\n")

    # ------------------------------------------------------------------ headline
    if summ:
        w("## Headline figures\n")
        rows = []
        for role in ("controller", "node"):
            peak = max(((x[role] or {}).get("rss_mb_peak") or 0) for x in summ["scenarios"])
            cpu_peak = max(((x[role] or {}).get("cpu_peak_pct") or 0) for x in summ["scenarios"])
            idle = (sc.get("idle-baseline", {}).get(role) or {})
            fin = (sc.get("idle-after", {}).get(role) or {})
            rows.append([role, idle.get("rss_mb_end"), peak, fin.get("rss_mb_end"), idle.get("cpu_avg_pct"), cpu_peak,
                         f"{fmt(idle.get('goroutines_end'))} → {fmt(fin.get('goroutines_end'))}",
                         f"{fmt(idle.get('rest_conns_end'))} → {fmt(fin.get('rest_conns_end'))}"])
        w(table(["Process", "Idle RSS MB", "Peak RSS MB", "RSS after load MB", "Idle CPU %", "Peak CPU % (1 s)",
                 "Goroutines idle → after", "REST conns idle → after"], rows))
        w("\nCPU % is of one core. \"After\" is the final idle period, once every scenario has finished and cleaned up.\n")

    # ------------------------------------------------------------------ per scenario
    if summ:
        w("## Driver footprint per scenario\n")
        for role in ("controller", "node"):
            w(f"### {role.capitalize()} process\n")
            rows = []
            for x in summ["scenarios"]:
                r = x[role] or {}
                rows.append([x["name"], x["duration_s"], r.get("cpu_s"), r.get("cpu_avg_pct"), r.get("cpu_peak_pct"),
                             r.get("rss_mb_peak"), r.get("rss_mb_end"), r.get("heap_inuse_mb_peak"),
                             f"{r.get('goroutines_start')}/{r.get('goroutines_peak')}/{r.get('goroutines_end')}",
                             r.get("threads_peak"), r.get("fds_peak"),
                             f"{r.get('rest_conns_peak')}/{r.get('rest_conns_end')}",
                             r.get("mounts_peak") if role == "node" else r.get("api_requests"),
                             r.get("nfs_conns_peak") if role == "node" else r.get("rpcs")])
            last = ["Mounts peak", "NFS conns peak"] if role == "node" else ["REST calls", "RPCs"]
            w(table(["Scenario", "Wall s", "CPU s", "CPU avg %", "CPU peak %", "RSS peak MB", "RSS end MB",
                     "Heap peak MB", "Goroutines start/peak/end", "Threads peak", "FDs peak", "REST conns peak/end"] + last, rows))
            w("")

        # ------------------------------------------------------------------ per operation
        w("## Cost per operation\n")
        w("Each row is one phase of one scenario on one array. **REST/RPC** counts the Qumulo REST calls the driver "
          "made per CSI call (from its own `csi_qumulo_api_requests_total`); **CPU ms/RPC** is the serving process's CPU "
          "time over the phase divided by the RPCs in it.\n")
        rows = []
        for x in summ["scenarios"]:
            for side, o in (x.get("ops") or {}).items():
                for ph, p in o["phases"].items():
                    if not p["rpcs"]:
                        continue
                    op = {"create": "CreateVolume", "expand": "ControllerExpandVolume", "snapshot-create": "CreateSnapshot",
                          "snapshot-delete": "DeleteSnapshot", "publish": "NodePublishVolume", "stats": "NodeGetVolumeStats",
                          "unpublish": "NodeUnpublishVolume", "delete": "DeleteVolume"}.get(ph, ph)
                    lat = o["latency_ms"].get(op, {})
                    codes = ", ".join(f"{k} {v}" for k, v in o["codes"].get(op, {}).items())
                    if o.get("aborted_retries", {}).get(op):
                        codes += f" ({o['aborted_retries'][op]} Aborted retried)"
                    rows.append([x["name"], side, op, p["rpcs"], codes, p["rpc_per_s"], p["api_per_rpc"], p["cpu_ms_per_rpc"],
                                 lat.get("p50"), lat.get("p95"), lat.get("max"), p["goroutines_peak"], p["rest_conns_peak"]])
        w(table(["Scenario", "Array", "RPC", "Calls", "Result codes", "RPC/s", "REST/RPC", "CPU ms/RPC",
                 "p50 ms", "p95 ms", "max ms", "Goroutines peak", "REST conns peak"], rows))
        w("")
        errs = [(x["name"], s, e, n) for x in summ["scenarios"] for s, o in (x.get("ops") or {}).items()
                for e, n in o["errors"].items()]
        if errs:
            w("### Errors returned\n")
            w(table(["Scenario", "Array", "Error (last line)", "Count"], [[a, b, f"`{c}`", d] for a, b, c, d in errs]))
            w("")

        # ------------------------------------------------------------------ REST breakdown
        bd = summ.get("controller_api_breakdown") or {}
        if bd:
            w("## REST calls by endpoint (controller, whole run)\n")
            rows = sorted(bd.items(), key=lambda kv: -kv[1])[:30]
            w(table(["Series", "Calls"], [[f"`{k.replace('csi_qumulo_api_requests_total', '')}`", int(v)] for k, v in rows]))
            w("")
        nb = summ.get("node_api_breakdown") or {}
        if nb:
            w("Node process REST calls: " + ", ".join(f"`{k.replace('csi_qumulo_api_requests_total', '')}` {int(v)}"
                                                   for k, v in sorted(nb.items(), key=lambda kv: -kv[1])[:10]) + "\n")

    # ------------------------------------------------------------------ array side usage
    w("## Array-side usage by CSI\n")
    rows = []
    for s in "AB":
        if not base[s]:
            continue
        b, a = csi_counts(base[s]), csi_counts(after[s] or base[s])
        for k in b:
            rows.append([s, k.replace("_", " "), b[k], a[k], a[k] - b[k]])
    w(table(["Array", "Object", "Before", "After", "Δ"], rows))
    w(f"\n**Objects left by this run** (name prefix `{meta.get('name_prefix', 'csi-rcr')}`):\n\n```\n" + left.strip() + "\n```\n")
    for s in "AB":
        b = base[s]
        if not b:
            continue
        w(f"### Array {s}: what is on it\n")
        w(f"- Capacity: {used(b) / MiB:.1f} MiB used of {int(b['file_system']['total_size_bytes']) / GiB:.1f} GiB; "
          f"snapshots hold {int(b['file_system']['snapshot_size_bytes']) / MiB:.2f} MiB. "
          f"Protection {b['protection']['data_blocks_per_stripe']}+{b['protection']['blocks_per_stripe'] - b['protection']['data_blocks_per_stripe']}, "
          f"restriper {b['restriper']['status']}.")
        w(f"- Exports ({len(b['exports'])}): " + "; ".join(f"`{e['export_path']}`→`{e['fs_path']}`" for e in b["exports"][:12]))
        q = b.get("quotas") or []
        if q:
            w(f"- Quotas ({len(q)}): " + "; ".join(f"`{x['path']}` {int(x['capacity_usage']) / 1024:.0f} KiB of {int(x['limit']) / GiB:.0f} GiB" for x in q[:10]))
        w(f"- Snapshots: {len(b.get('snapshots') or [])} ({', '.join(f'{k} {v}' for k, v in (b.get('snapshot_name_kinds') or {}).items())}); "
          f"policies: {', '.join(p['name'] for p in b.get('snapshot_policies') or []) or 'none'}")
        rt = b.get("replication_target") if isinstance(b.get("replication_target"), list) else []
        rs = b.get("replication_source") if isinstance(b.get("replication_source"), list) else []
        w(f"- Replication: {len(rs)} source, {len(rt)} target relationship(s)"
          + ("; states " + ", ".join(sorted({r.get('state', '?') for r in rs + rt})) if rs + rt else ""))
        big = sorted(b.get("dir_aggregates", []), key=lambda d: -d["dirs"])[:6]
        w("- Busiest directories: " + "; ".join(f"`{d['path']}` {d['dirs']} dirs / {d['files']} files / {d['capacity_bytes'] / 1024:.0f} KiB" for d in big))
        w(f"- REST connections at baseline: {b['connections']['by_type']} from {b['connections']['by_address']}\n")

    # ------------------------------------------------------------------ array load
    if summ:
        w("## Array health and load during the run\n")
        w("From each array's own analytics (`/v1/analytics/time-series`, 5 s resolution) over each scenario's window, "
          "plus a 10 s REST probe (`/v2/network/connections/`).\n")
        rows = []
        for x in summ["scenarios"]:
            for s in "AB":
                an = x["array_analytics"].get(s, {})
                g = lambda k, f="max": (an.get(k) or {}).get(f)
                smp = x["array_sampler"][s]
                rows.append([x["name"], s, g("iops.total.rate"), g("iops.write.rate"), g("throughput.total.rate"),
                             g("latency.metadata.rate"), g("latency.write.rate"), smp["rest_conns_peak"], smp["nfs_conns_peak"],
                             smp["rest_probe_ms_p50"], smp["rest_probe_ms_max"], smp["errors"]])
        w(table(["Scenario", "Array", "IOPS max", "Write IOPS max", "Throughput max B/s", "Metadata latency max (API units)",
                 "Write latency max (API units)", "REST conns peak", "NFS conns peak", "REST probe p50 ms", "REST probe max ms",
                 "Probe errors"], rows))
        w("")
        for s in "AB":
            b = base[s]
            if b:
                net = "; ".join(f"{n['node']} {n['speed_mbps']} Mb/s" for n in b["network"])
                w(f"- Array {s} nodes: {net}. Floating addresses: "
                  f"{sum(len(a['floating']) for n in b['network'] for a in n['addresses'])}.")
        w("")

    # ------------------------------------------------------------------ sizing
    if summ and meta.get("chart_requests"):
        w("## Measured use against the chart's resource settings\n")
        cr = meta["chart_requests"]
        rows = []
        for role in ("controller", "node"):
            peak_rss = max(((x[role] or {}).get("rss_mb_peak") or 0) for x in summ["scenarios"])
            idle_cpu = (sc.get("idle-baseline", {}).get(role) or {}).get("cpu_avg_pct")
            busy = max(((x[role] or {}).get("cpu_avg_pct") or 0) for x in summ["scenarios"])
            rows.append([role, cr.get(role, "none"), idle_cpu * 10 if idle_cpu is not None else None, busy * 10, peak_rss])
        w(table(["Process", "Chart requests (driver container)", "Idle CPU (millicores)", "Busiest scenario avg CPU (millicores)",
                 "Peak RSS MB"], rows))
        w("")

    # ------------------------------------------------------------------ method
    w("## Method\n")
    w(meta.get("method", "See test/resource-report/README.md."))
    w("")
    out.write_text("\n".join(L) + "\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
